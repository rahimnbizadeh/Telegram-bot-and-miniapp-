"""تبدیل تاریخ میلادی به شمسی (برای نمایش «آخرین ورود» و ...) بدون وابستگی خارجی"""
import datetime

_IRAN = datetime.timezone(datetime.timedelta(hours=3, minutes=30))
_G_D_M = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334]


def gregorian_to_jalali(gy: int, gm: int, gd: int):
    if gy > 1600:
        jy, gy = 979, gy - 1600
    else:
        jy, gy = 0, gy - 621
    gy2 = gy + 1 if gm > 2 else gy
    days = 365 * gy + (gy2 + 3) // 4 - (gy2 + 99) // 100 + (gy2 + 399) // 400 - 80 + gd + _G_D_M[gm - 1]
    jy += 33 * (days // 12053)
    days %= 12053
    jy += 4 * (days // 1461)
    days %= 1461
    if days > 365:
        jy += (days - 1) // 365
        days = (days - 1) % 365
    if days < 186:
        jm, jd = 1 + days // 31, 1 + days % 31
    else:
        jm, jd = 7 + (days - 186) // 30, 1 + (days - 186) % 30
    return jy, jm, jd


def format_jalali_datetime(ts: float) -> str:
    """مثلاً «1405/08/10 - 02:57» به وقت ایران (ارقام لاتین)"""
    d = datetime.datetime.fromtimestamp(ts, _IRAN)
    jy, jm, jd = gregorian_to_jalali(d.year, d.month, d.day)
    return f"{jy}/{jm:02d}/{jd:02d} - {d.hour:02d}:{d.minute:02d}"
